export interface RenderOptions {
  width?: number;
  scale?: number;
  padding?: number;
  lineSpacing?: number;
  /** Adds light speckle so the file looks like a scan rather than a bitmap. */
  noise?: number;
}

export function renderTextPng(lines: string[], options: RenderOptions = {}): Buffer {
  const scale = options.scale ?? 4;
  const padding = options.padding ?? 24;
  const lineSpacing = options.lineSpacing ?? 6;
  const glyphWidth = 6 * scale;
  const glyphHeight = 7 * scale;
  const lineHeight = glyphHeight + lineSpacing * scale;

  const longest = lines.reduce((max, line) => Math.max(max, line.length), 0);
  // Floored to a phone-camera sized frame so a short document still looks
  // like a photo of a page rather than a cropped thumbnail.
  const width = options.width ?? Math.max(640, padding * 2 + longest * glyphWidth);
  const height = Math.max(640, padding * 2 + lines.length * lineHeight);

  const pixels = Buffer.alloc(width * height, 0xff);

  lines.forEach((line, lineIndex) => {
    const top = padding + lineIndex * lineHeight;
    const text = line.toUpperCase();
    for (let charIndex = 0; charIndex < text.length; charIndex += 1) {
      const glyph = GLYPHS[text[charIndex]] ?? GLYPHS[' '];
      const left = padding + charIndex * glyphWidth;
      for (let row = 0; row < 7; row += 1) {
        for (let col = 0; col < 5; col += 1) {
          if (glyph[row][col] !== '1') continue;
          for (let dy = 0; dy < scale; dy += 1) {
            for (let dx = 0; dx < scale; dx += 1) {
              const x = left + col * scale + dx;
              const y = top + row * scale + dy;
              if (x < width && y < height) pixels[y * width + x] = 0x20;
            }
          }
        }
      }
    }
  });

  if (options.noise) {
    for (let i = 0; i < pixels.length; i += 1) {
      if (Math.random() < options.noise) {
        pixels[i] = Math.max(0, Math.min(255, pixels[i] - Math.floor(Math.random() * 60)));
      }
    }
  }

  return encodeGrayscalePng(pixels, width, height);
}

function encodeGrayscalePng(pixels: Buffer, width: number, height: number): Buffer {
  const raw = Buffer.alloc((width + 1) * height);
  for (let y = 0; y < height; y += 1) {
    raw[y * (width + 1)] = 0; // filter type: none
    pixels.copy(raw, y * (width + 1) + 1, y * width, (y + 1) * width);
  }

  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 0; // colour type: grayscale
  ihdr[10] = 0;
  ihdr[11] = 0;
  ihdr[12] = 0;

  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', zlib.deflateSync(raw, { level: 6 })),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}

function chunk(type: string, data: Buffer): Buffer {
  const length = Buffer.alloc(4);
  length.writeUInt32BE(data.length, 0);
  const typeAndData = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(typeAndData), 0);
  return Buffer.concat([length, typeAndData, crc]);
}

const CRC_TABLE = (() => {
  const table = new Uint32Array(256);
  for (let n = 0; n < 256; n += 1) {
    let c = n;
    for (let k = 0; k < 8; k += 1) {
      c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    }
    table[n] = c >>> 0;
  }
  return table;
})();

function crc32(buffer: Buffer): number {
  let crc = 0xffffffff;
  for (const byte of buffer) crc = CRC_TABLE[(crc ^ byte) & 0xff] ^ (crc >>> 8);
  return (crc ^ 0xffffffff) >>> 0;
}
